#!/usr/bin/env python3
"""Writes the compiled-in menu of pitrex/loader/loaderMain.c as C test data: a mock
MenuItemNew array with the real ids, names, images, parameters and links.
   python3 -I docs/tools/gen_menu_tree.py pitrex/loader/loaderMain.c > menu_tree.inc
Used by docs/tools/test_new_menu.c."""
import re, sys

src = open(sys.argv[1], encoding='latin-1').read()
items = {}
for m in re.finditer(r'MenuItemNew\s+(\w+)\s*=\s*\{(.*?)\n\};', src, re.S):
    body = re.sub(r'//[^\n]*', '', m.group(2))
    f = []; cur = ''; q = False; d = 0; esc = False
    for ch in body:
        if q:
            cur += ch
            if esc: esc = False
            elif ch == '\\': esc = True
            elif ch == '"': q = False
            continue
        if ch == '"': q = True
        if ch in '{(': d += 1
        if ch in '})': d -= 1
        if ch == ',' and d == 0:
            f.append(cur.strip()); cur = ''; continue
        cur += ch
    f.append(cur.strip())
    items[m.group(1)] = f

STR = r'"((?:[^"\\]|\\.)*)"'
def cdecode(s):
    return s  # keep the C escapes as written: they are pasted back into C source

def cstr(x):
    m = re.fullmatch(STR, x.strip())
    return '"%s"' % m.group(1) if m else '0'
def img(x):
    m = re.match(r'IMG_FILE_PREFIX\s*' + STR, x.strip())
    return '"piZero1/%s"' % m.group(1) if m else '0'
def ref(x):
    x = x.strip().lstrip('&')
    return x if x and x != '0' else ''

order = []; seen = set()
def visit(n):
    if n in seen or n not in items: return
    seen.add(n); order.append(n)
    c = ref(items[n][9])
    while c and c in items and c not in seen:
        visit(c)
        c = ref(items[c][11])
for top in ('vectrexMenu', 'arcadeMenu', 'computerMenu', 'videoMenu', 'audioMenu'):
    visit(top)
idx = {n: i for i, n in enumerate(order)}
print('/* generated by gen_menu_tree.py from loaderMain.c */')
print('#define MOCK_COUNT %d' % len(order))
print('static MenuItemNew mock[MOCK_COUNT];')
print('static void mockInit(void)\n{')
for n in order:
    f = items[n]; i = idx[n]
    # param strings keep their C escapes (\\x2d etc.)
    print('  mock[%d].id = %s; mock[%d].DISPLAYNAME = %s; mock[%d].img = %s; mock[%d].param1 = %s; mock[%d].param2 = %s; /* %s */'
          % (i, f[0], i, cstr(f[1]), i, img(f[3]), i, cstr(f[4]), i, cstr(f[5]), n))
    texts = [cdecode(x) for x in re.findall(STR, ' '.join(f[13:]))]
    for k, t in enumerate(texts[:11]):
        print('  mock[%d].text[%d] = "%s";' % (i, k, t))
    c = ref(f[9]); r = ref(f[11])
    if c in idx: print('  mock[%d].child = &mock[%d];' % (i, idx[c]))
    if r in idx and n not in ('vectrexMenu', 'arcadeMenu', 'computerMenu', 'videoMenu', 'audioMenu'):
        print('  mock[%d].right = &mock[%d];' % (i, idx[r]))
print('}')
print('static MenuItemNew *mockTops[5];')
print('static void mockTopsInit(void)\n{')
for k, top in enumerate(('vectrexMenu', 'arcadeMenu', 'computerMenu', 'videoMenu', 'audioMenu')):
    print('  mockTops[%d] = &mock[%d];' % (k, idx[top]))
print('}')
